<!--
  ============================================================
  교재 91p | Vue Directive - v-once
  ============================================================
  [핵심] 최초 1회만 렌더링하고, 그 이후 데이터가 바뀌어도 DOM을 갱신하지 않는다.

  [헷갈리지 말 것 — 강사님이 짚어주신 부분]
    값이 안 올라가는 게 아니다. count 변수의 '값'은 계속 올라간다.
    다만 v-once가 붙은 자리의 '화면'만 최초 값(1)에 얼어붙는 것이다.

  [왜 쓰는가?]
    Vue가 반응형 데이터를 실시간 감시하려면 메모리를 계속 소모한다.
    약관 내용, 소개글처럼 백엔드에서 한 번 받아온 뒤 절대 안 바뀌는
    데이터에 v-once를 붙이면 Vue가 감시를 그만두어 부담이 준다.

  [중요도] 중간. v-pre / v-cloak 보다는 쓸 일이 있다. (강사님)
-->
<script setup>
import { ref } from 'vue'

const count = ref(1)
</script>

<template>
  <div class="practice-section">
    <h2>v-once 디렉티브 학습</h2>
    <!-- 버튼을 누를 때마다 올라간다 -->
    <p>일반 변수 (실시간): {{ count }}</p>
    <!-- 아무리 눌러도 1에 고정된다 (값은 올라가지만 화면만 안 바뀜) -->
    <p v-once>v-once 변수 (최초 고정): {{ count }}</p>
    <button @click="count++">숫자 증가 버튼</button>
  </div>
</template>
