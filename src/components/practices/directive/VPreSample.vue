<!--
  ============================================================
  교재 89p | Vue Directive - v-pre
  ============================================================
  [핵심] "Vue야, 여기는 해석하지 말고 적힌 그대로 뿌려라"

  Vue 엔진은 HTML을 읽다가 {{ }} 나 v- 디렉티브를 만나면
  자바스크립트 데이터로 갈아끼우는 연산을 한다.
  v-pre가 붙은 태그와 그 '자식 태그들'은 그 연산을 전부 건너뛴다.

  [실무 활용] Vue 문법 자체를 화면에 설명해야 할 때 (문서/튜토리얼 페이지).
              이 프로젝트에서도 VHtmlSample / VTextSample 의 제목에
              "{{ }}" 를 글자로 보여주려고 v-pre를 실제로 썼다.

  [중요도] 낮음. 그런 게 있다는 정도만 알면 된다. (강사님)
-->
<script setup>
import { ref } from 'vue'

const message = ref('안녕하세요!')
</script>

<template>
  <div class="practice-section">
    <h2>v-pre 디렉티브 학습</h2>
    <!-- 해석됨 → '안녕하세요!' 가 나온다 -->
    <p>일반 출력: {{ message }}</p>
    <!-- 해석 안 됨 → 중괄호와 변수명이 글자 그대로 나온다 -->
    <p v-pre>v-pre 출력: {{ message }}</p>
  </div>
</template>
